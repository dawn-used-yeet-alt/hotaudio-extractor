#!/bin/sh
# Installs hotaudio-download for this machine.
#
# It is attached to every release so it can be piped straight into a shell:
#
#   curl -fsSL https://github.com/dawn-used-yeet-alt/hotaudio-extractor/releases/latest/download/install.sh | sh
#
# Archive names carry no version, so that URL and the mapping below are stable
# across releases. `--print` resolves the archive without downloading anything.
#
# Overrides, used by CI to exercise the mapping without the matching hardware
# (and by anyone cross-installing for another machine):
#   HOTAUDIO_OS    what `uname -s` would print  (Linux, Darwin)
#   HOTAUDIO_ARCH  what `uname -m` would print  (x86_64, aarch64, arm64)
#   HOTAUDIO_DIR   install directory
#   HOTAUDIO_BASE  release download URL base
#   HOTAUDIO_SHELL shell to install completions for (default: $SHELL)
set -eu

repo=dawn-used-yeet-alt/hotaudio-extractor
base=${HOTAUDIO_BASE:-https://github.com/${repo}/releases/latest/download}
docs="https://github.com/${repo}/blob/main/docs/INSTALL.md"
os=${HOTAUDIO_OS:-$(uname -s)}
arch=${HOTAUDIO_ARCH:-$(uname -m)}

die() {
  printf 'install.sh: %s\n' "$*" >&2
  exit 1
}

# Termux runs on Android and installs into its own prefix.
termux=false
case "${PREFIX:-}" in *com.termux*) termux=true ;; esac

case "$os" in
  Linux)
    if [ "$termux" = true ]; then
      case "$arch" in
        aarch64 | arm64) slug=android-arm64 ;;
        x86_64 | amd64) slug=android-x86_64 ;;
        *) die "no Termux build for '$arch'; see $docs" ;;
      esac
    else
      # Static: it needs no libc, so there is no reason to guess between glibc
      # and musl hosts.
      case "$arch" in
        x86_64 | amd64) slug=linux-x86_64-static ;;
        aarch64 | arm64) slug=linux-arm64-static ;;
        *) die "no Linux build for '$arch'; see $docs" ;;
      esac
    fi
    ;;
  Darwin)
    case "$arch" in
      x86_64 | amd64) slug=macos-x86_64 ;;
      aarch64 | arm64) slug=macos-arm64 ;;
      *) die "no macOS build for '$arch'; see $docs" ;;
    esac
    ;;
  *)
    die "no prebuilt binary for '$os'. Windows and manual installs are in $docs"
    ;;
esac

archive="hotaudio-download-${slug}.tar.gz"

if [ "$termux" = true ]; then
  dir=${HOTAUDIO_DIR:-$PREFIX/bin}
else
  dir=${HOTAUDIO_DIR:-$HOME/.local/bin}
fi

# Completions are generated by the binary that was just installed
# (`--completions <shell>`), so they cannot drift from it and need no second
# download. Installed per user, next to where each shell looks on its own.
completions=ask
shell=$(basename "${HOTAUDIO_SHELL:-${SHELL:-}}" 2>/dev/null || true)
case "$shell" in
  bash | zsh | fish) ;;
  none) completions=no ;;
  *) shell= ;;
esac

completion_path() {
  case "$1" in
    bash) printf '%s/bash-completion/completions/hotaudio-download' "${XDG_DATA_HOME:-$HOME/.local/share}" ;;
    zsh) printf '%s/.zfunc/_hotaudio-download' "${ZDOTDIR:-$HOME}" ;;
    fish) printf '%s/fish/completions/hotaudio-download.fish' "${XDG_CONFIG_HOME:-$HOME/.config}" ;;
    *) return 1 ;;
  esac
}

mode=install
while [ $# -gt 0 ]; do
  case "$1" in
    --print) mode=print ;;
    --dir)
      shift
      [ $# -gt 0 ] || die "--dir needs a value"
      dir=$1
      ;;
    --completions)
      completions=yes
      if [ $# -gt 1 ]; then
        case "$2" in
          bash | zsh | fish)
            shell=$2
            shift
            ;;
        esac
      fi
      ;;
    --completions=*)
      completions=yes
      shell=${1#--completions=}
      case "$shell" in bash | zsh | fish) ;; *) die "--completions takes bash, zsh or fish" ;; esac
      ;;
    --no-completions) completions=no ;;
    --help | -h) mode=help ;;
    *) die "unknown option '$1' (try --help)" ;;
  esac
  shift
done

case "$mode" in
  print)
    printf '%s\n' "$archive"
    exit 0
    ;;
  help)
    cat <<EOF
Install hotaudio-download for this machine.

Usage: install.sh [--dir DIR] [--completions [SHELL]] [--no-completions] [--print]

  --dir DIR            install into DIR instead of \$HOME/.local/bin
  --completions [SHELL]  install the completion without asking (bash, zsh, fish;
                         default: the shell that runs the installer)
  --no-completions     do not offer a completion
  --print              print the archive this machine needs, and stop
  --help               print this text

By default the completion for your shell (\$SHELL) is offered after the binary
and installed only if you say yes. A completion is a file in your own home
directory; nothing system-wide is touched.

Environment: HOTAUDIO_DIR, HOTAUDIO_SHELL, HOTAUDIO_OS, HOTAUDIO_ARCH,
HOTAUDIO_BASE. HOTAUDIO_SHELL=none skips completions.
Every platform, and manual downloads: $docs
EOF
    exit 0
    ;;
esac

if command -v curl >/dev/null 2>&1; then
  fetch() { curl -fsSL "$1" -o "$2"; }
elif command -v wget >/dev/null 2>&1; then
  fetch() { wget -qO "$2" "$1"; }
else
  die "curl or wget is required"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT INT TERM

printf 'Downloading %s\n' "$archive"
fetch "$base/$archive" "$tmp/$archive" || die "could not download $archive"

# The checksums are advisory: a missing tool or a missing SHA256SUMS.txt is a
# warning, a mismatch is fatal.
if fetch "$base/SHA256SUMS.txt" "$tmp/SHA256SUMS.txt" 2>/dev/null; then
  expected=$(grep " \./${archive}\$" "$tmp/SHA256SUMS.txt" | head -1 | cut -d' ' -f1)
  if command -v sha256sum >/dev/null 2>&1; then
    actual=$(sha256sum "$tmp/$archive" | cut -d' ' -f1)
  elif command -v shasum >/dev/null 2>&1; then
    actual=$(shasum -a 256 "$tmp/$archive" | cut -d' ' -f1)
  else
    actual=
  fi
  if [ -n "$expected" ] && [ -n "$actual" ]; then
    [ "$expected" = "$actual" ] || die "checksum mismatch for $archive"
    printf 'Checksum ok\n'
  else
    printf 'install.sh: could not verify the checksum\n' >&2
  fi
fi

tar -xzf "$tmp/$archive" -C "$tmp" || die "could not extract $archive"
src="$tmp/hotaudio-download-$slug/hotaudio-download"
[ -f "$src" ] || die "unexpected archive layout in $archive"

mkdir -p "$dir" || die "could not create $dir"
cp "$src" "$dir/hotaudio-download" || die "could not write $dir/hotaudio-download"
chmod 755 "$dir/hotaudio-download"

version=$("$dir/hotaudio-download" --version 2>/dev/null || true)
if [ -n "$version" ]; then
  printf 'Installed %s\n' "$version"
else
  printf 'Installed %s/hotaudio-download\n' "$dir"
fi

# --- shell completions ---
# Offered rather than imposed: `--no-completions` skips it, and an install with
# no terminal (piped into `sh` from a CI job) takes the default instead of
# blocking on a read. A completion is a file in the user's own directories;
# nothing system-wide is touched.
#
# The terminal test runs in a subshell on purpose: in dash a failed `</dev/tty`
# redirection ends the whole script, even inside a denied `if` condition.
if [ "$completions" = ask ]; then
  answer=
  prompted=false
  if [ -t 0 ]; then
    printf '\nInstall shell completions for %s? [Y/n] (or bash, zsh, fish): ' "${shell:-your shell}" >&2
    read -r answer || answer=
    prompted=true
  elif ( : </dev/tty ) 2>/dev/null; then
    # `curl ... | sh` feeds the script on stdin, so ask the terminal instead.
    printf '\nInstall shell completions for %s? [Y/n] (or bash, zsh, fish): ' "${shell:-your shell}" >&2
    read -r answer </dev/tty || answer=
    prompted=true
  fi
  if [ "$prompted" = true ]; then
    case "$answer" in
      '' | [Yy] | [Yy][Ee][Ss]) ;;
      [Nn] | [Nn][Oo] | none) completions=no ;;
      bash | zsh | fish) shell=$answer ;;
      *)
        printf 'install.sh: no completion for %s\n' "$answer" >&2
        completions=no
        ;;
    esac
  fi
fi

if [ "$completions" != no ]; then
  if [ -z "$shell" ]; then
    printf 'install.sh: no completion for your shell; --completions bash|zsh|fish installs one\n' >&2
  else
    target=$(completion_path "$shell")
    # The binary prints its own completion, so it matches the binary just
    # installed and needs no second download.
    if mkdir -p "$(dirname "$target")" 2>/dev/null &&
      "$dir/hotaudio-download" --completions "$shell" >"$target" 2>/dev/null; then
      printf 'Completions: %s\n' "$target"
      if [ "$shell" = zsh ]; then
        printf '  zsh loads it only if that directory is on fpath; add this to ~/.zshrc\n  before compinit:\n    fpath=(%s $fpath)\n' "$(dirname "$target")"
      fi
    else
      rm -f "$target" 2>/dev/null || true
      printf 'install.sh: could not install %s completions\n' "$shell" >&2
    fi
  fi
fi

case ":${PATH}:" in
  *":$dir:"*) ;;
  *)
    cat <<EOF

$dir is not on your PATH. Add it, then reload your shell:

  export PATH="$dir:\$PATH"
EOF
    ;;
esac

printf '\nTry it:\n  hotaudio-download "https://hotaudio.net/u/user/track-slug"\n'
