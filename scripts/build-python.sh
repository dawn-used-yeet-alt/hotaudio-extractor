#!/usr/bin/env bash
# Stage the generated Python bindings as an importable package and a wheel.
#
# UniFFI's Python output is a single ctypes module that loads `libhotaudio_ffi`
# from its own directory. This wraps it in a package with that library beside it,
# so `pip install` (or `PYTHONPATH`) just works, and builds a platform wheel with
# setuptools. The wheel is Python-version-independent because the binding is
# ctypes, not the CPython C API.
#
# Usage: scripts/build-python.sh [OUT_DIR] [--release]
#   OUT_DIR defaults to bindings/out/python.
set -euo pipefail

cd "$(dirname "$0")/.."

out="bindings/out/python"
release=0
for arg in "$@"; do
    case "$arg" in
        --release) release=1 ;;
        --*) echo "error: unknown flag $arg" >&2; exit 2 ;;
        *) out="$arg" ;;
    esac
done

if [ "$release" = 1 ]; then
    scripts/build-bindings.sh "$out/gen" --release
    profile=release
else
    scripts/build-bindings.sh "$out/gen"
    profile=debug
fi

case "$(uname -s)" in
    Darwin) lib="libhotaudio_ffi.dylib" ;;
    MINGW* | MSYS* | CYGWIN*) lib="hotaudio_ffi.dll" ;;
    *) lib="libhotaudio_ffi.so" ;;
esac

stage="$out/pkg"
package="$stage/hotaudio_ffi"
rm -rf "$stage" "$out/dist"
mkdir -p "$package" "$out/dist"

cp "$out/gen/hotaudio_ffi.py" "$package/hotaudio_ffi.py"
cp "bindings/target/$profile/$lib" "$package/$lib"

cat > "$package/__init__.py" <<'PY'
"""hotaudio.net audio extraction for Python.

The blocking functions come from the generated UniFFI module. Call them from a
worker thread, or wrap them with ``asyncio.to_thread``.
"""

from .hotaudio_ffi import *  # noqa: F401,F403
PY

version=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)

# `has_ext_modules` is what makes the wheel platform-specific. Without it
# setuptools sees only Python sources and tags the artifact `py3-none-any`,
# which would install a Linux `.so` on any machine. `get_tag` keeps the
# platform but drops the CPython ABI tag: the binding is ctypes, so one wheel
# works on every Python 3 version of that platform.
cat > "$stage/setup.py" <<'PY'
from setuptools import Distribution, setup


class BinaryDistribution(Distribution):
    def has_ext_modules(self):
        return True

    def get_tag(self):
        _, _, platform = super().get_tag()
        return "py3", "none", platform


setup(distclass=BinaryDistribution)
PY

cat > "$stage/pyproject.toml" <<EOF
[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "hotaudio-ffi"
version = "$version"
description = "UniFFI bindings for the hotaudio audio extractor"
readme = "README.md"
requires-python = ">=3.8"
license = { text = "MIT" }

[tool.setuptools]
packages = ["hotaudio_ffi"]

[tool.setuptools.package-data]
hotaudio_ffi = ["*"]
EOF

cat > "$stage/README.md" <<'MD'
Python bindings for the hotaudio audio extractor. Generated by UniFFI; the
blocking functions are meant to run on a worker thread.
MD

python3 -m pip wheel --no-deps --wheel-dir "$out/dist" "$stage"

echo "staged package: $stage/hotaudio_ffi"
echo "wheel: $(ls "$out"/dist/*.whl)"
